#!/usr/bin/env python3
"""Writes src/host/pad_glyphs_data.h from the SVGs in external/controllerimage, so the
button icons are built into lpn-host and lpn-launcher (no files to ship beside them)."""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
art = root / "external/controllerimage"
out = root / "src/host/pad_glyphs_data.h"
# The order pad_glyphs.cpp indexes: style, then south, east, west, north.
styles = ["ps5", "xboxone", "joyconpair"]
lines = ["// Generated by scripts/embed-pad-glyphs.py from external/controllerimage. Do not edit.",
         "#pragma once", "", "namespace host::glyph_data {", "",
         "constexpr const char* kSvgs[3][4] = {"]
for s in styles:
    lines.append("    {")
    for b in "sewn":
        text = (art / s / f"{b}.svg").read_text().replace("\n", " ").strip()
        lines.append(f'        R"svg({text})svg",')
    lines.append("    },")
lines += ["};", "", "} // namespace host::glyph_data", ""]
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)}")
